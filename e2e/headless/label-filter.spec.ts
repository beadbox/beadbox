import { expect, test } from "../fixtures/harness"
import { type Listed, openTree, renderedIds } from "./helpers"

test("label selection matches bd, composes, clears, persists and resets on workspace switch", async ({ page, workspace: ws, statusesWorkspace }) => {
  test.setTimeout(60_000)
  const listed = ws.bdJson<Listed[]>(["list", "--status", "all", "--limit", "0", "--flat"])
  const targets = [listed.find((b) => b.title === "Critical Bug"), listed.find((b) => b.title === "High Priority Task")].filter((b): b is Listed => Boolean(b))
  expect(targets).toHaveLength(2)
  ws.bd(["update", targets[0].id, "--add-label=ttl-alpha"])
  ws.bd(["update", targets[1].id, "--add-label=ttl-beta"])
  const all = await openTree(page, ws)
  const before = await renderedIds(page)
  const trigger = page.getByRole("button", { name: "Label filter", exact: true })
  const row = (label: string) => page.locator("[data-multi-select-row]").filter({ has: page.getByRole("checkbox", { name: label, exact: true }) })
  await trigger.click()
  await row("ttl-alpha").click()
  await page.keyboard.press("Escape")
  const alpha = ws.bdJson<Listed[]>(["list", "--label=ttl-alpha", "--status", "all", "--limit", "0", "--flat"])
  expect(alpha.map((b) => b.id)).toEqual([targets[0].id])
  await expect(page.locator(`[data-item-id="${targets[0].id}"]`)).toBeVisible()
  await expect(page.locator(`[data-item-id="${targets[1].id}"]`)).toHaveCount(0)
  // Only the CLI match plus its ancestor context remains.
  await expect.poll(() => renderedIds(page)).toEqual(before.filter((id) => id === targets[0].id || all.find((b) => b.id === id)?.issue_type === "epic"))
  await trigger.click()
  await row("ttl-beta").click()
  await page.keyboard.press("Escape")
  for (const target of targets) await expect(page.locator(`[data-item-id="${target.id}"]`)).toBeVisible()
  await page.screenshot({ path: test.info().outputPath("label-filter-selected.png") })
  await page.getByPlaceholder("Search by title or ID...").fill(targets[0].id)
  await expect(page.locator(`[data-item-id="${targets[1].id}"]`)).toHaveCount(0)
  await page.getByPlaceholder("Search by title or ID...").fill("")
  await page.reload()
  await expect(trigger).toHaveText("2 labels")
  await trigger.click()
  await row("All Labels").click()
  await page.keyboard.press("Escape")
  await expect(trigger).toHaveText("All Labels")
  // A bd edit refreshes the choices without navigation or reload.
  await trigger.click()
  ws.bd(["update", targets[0].id, "--add-label=ttl-live"])
  await expect(row("ttl-live")).toBeVisible({ timeout: 10_000 })
  await row("ttl-live").click()
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: `Open ${statusesWorkspace.name}`, exact: true }).click()
  await expect(trigger).toHaveText("All Labels")
  await expect(page.locator("[data-item-id]").first()).toBeVisible()
  await trigger.click()
  await expect(row("ttl-live")).toHaveCount(0)
})
