import { expect, test } from "../fixtures/harness"
import { type Listed, openTree, renderedIds } from "./helpers"

test("label selection matches bd, composes, clears, persists and resets on workspace switch", async ({ page, workspace: ws, statusesWorkspace }) => {
  test.setTimeout(60_000)
  const listed = ws.bdJson<Listed[]>(["list", "--status", "all", "--limit", "0", "--flat"])
  const targets = [listed.find((b) => b.title === "Critical Bug"), listed.find((b) => b.title === "High Priority Task")].filter((b): b is Listed => Boolean(b))
  expect(targets).toHaveLength(2)
  ws.bd(["update", targets[0].id, "--add-label=ttl-alpha"])
  ws.bd(["update", targets[1].id, "--add-label=ttl-beta"])
  const epic = listed.find((b) => b.title === "E2E Test Epic")!
  const unrelated = ws.bdJson<Listed>(["create", "Unrelated label epic", "--type=epic"])
  ws.bd(["create", "Unrelated label child", `--parent=${unrelated.id}`])
  const nested = ws.bdJson<Listed>(["create", "Nested label target", `--parent=${targets[1].id}`])
  ws.bd(["update", nested.id, "--add-label=ttl-alpha"])
  const closed = ws.bdJson<Listed>(["create", "Closed label target", `--parent=${epic.id}`])
  ws.bd(["update", closed.id, "--add-label=ttl-alpha", "--status=closed"])
  ws.bd(["update", targets[1].id, "--status=in_progress"])
  await openTree(page, ws)
  await page.locator(`[data-item-id="${targets[1].id}"] .bead-row-id button`).first().click()
  const trigger = page.getByRole("button", { name: "Label filter", exact: true })
  const row = (label: string) => page.locator("[data-multi-select-row]").filter({ has: page.getByRole("checkbox", { name: label, exact: true }) })
  await trigger.click()
  await row("ttl-alpha").click()
  await page.keyboard.press("Escape")
  const alpha = ws.bdJson<Listed[]>(["list", "--label=ttl-alpha", "--status", "all", "--limit", "0", "--flat"])
  expect(alpha.map((b) => b.id).sort()).toEqual([targets[0].id, nested.id, closed.id].sort())
  await expect(page.locator(`[data-item-id="${targets[0].id}"]`)).toBeVisible()
  await expect(page.locator(`[data-item-id="${nested.id}"]`)).toBeVisible()
  // Only the CLI match plus its ancestor context remains.
  await expect.poll(() => renderedIds(page)).toEqual([epic.id, targets[0].id, targets[1].id, nested.id, closed.id].sort())
  await expect(page.locator(`[data-item-id="${unrelated.id}"]`)).toHaveCount(0)
  await trigger.click()
  await row("ttl-beta").click()
  await page.keyboard.press("Escape")
  const any = ws.bdJson<Listed[]>(["list", "--label-any=ttl-alpha,ttl-beta", "--status", "all", "--limit", "0", "--flat"])
  expect(any.map((b) => b.id).sort()).toEqual([targets[0].id, targets[1].id, nested.id, closed.id].sort())
  await expect.poll(() => renderedIds(page)).toEqual([...any.map((b) => b.id), epic.id].sort())
  await page.screenshot({ path: test.info().outputPath("label-filter-selected.png") })
  // Select only Open, then intersect label ANY + status + search with bd.
  await page.getByRole("button", { name: "Status filter", exact: true }).click()
  await row("All Status").click()
  await row("Open").click()
  await page.keyboard.press("Escape")
  await page.getByPlaceholder("Search by title or ID...").fill("target")
  const composed = ws.bdJson<Listed[]>(["list", "--label-any=ttl-alpha,ttl-beta", "--status=open", "--title-contains=target", "--limit", "0", "--flat"])
  expect(composed.map((b) => b.id)).toEqual([nested.id])
  await expect.poll(() => renderedIds(page)).toEqual([epic.id, targets[1].id, nested.id].sort())
  await page.getByPlaceholder("Search by title or ID...").fill("")
  await page.getByRole("button", { name: "Status filter", exact: true }).click()
  await row("All Status").click()
  await page.keyboard.press("Escape")
  await page.reload()
  await expect(trigger).toHaveText("2 labels")
  await trigger.click()
  await row("All Labels").click()
  await page.keyboard.press("Escape")
  await expect(trigger).toHaveText("All Labels")
  // A bd edit refreshes the choices without navigation or reload.
  await trigger.click()
  ws.bd(["update", targets[0].id, "--add-label=ttl-live"])
  await expect(row("ttl-live")).toBeVisible({ timeout: 10_000 })
  await row("ttl-live").click()
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: `Open ${statusesWorkspace.name}`, exact: true }).click()
  await expect(trigger).toHaveText("All Labels")
  // The explicit status whitelist from the composition check persists across
  // workspaces. Select this workspace's custom statuses before checking rows.
  await page.getByRole("button", { name: "Status filter", exact: true }).click()
  await expect(row("Ticket Awaiting")).toBeVisible()
  await row("All Status").click()
  await page.keyboard.press("Escape")
  const switched = statusesWorkspace.bdJson<Listed[]>(["list", "--status", "all", "--limit", "0", "--flat"])
  await expect.poll(() => renderedIds(page)).toEqual(switched.map((b) => b.id).sort())
  await trigger.click()
  await expect(row("ttl-live")).toHaveCount(0)
})

for (const [view, path] of [["Chart", "/chart"], ["All projects", "/all-projects"]] as const) {
  test(`${view} lists unselected labels after a label is selected in Beads`, async ({ page, workspace: ws }) => {
    const beads = ws.bdJson<Listed[]>(["list", "--status", "all", "--limit", "0", "--flat"])
    const selected = beads.find((b) => b.title === "Critical Bug")!
    const other = beads.find((b) => b.title === "High Priority Task")!
    ws.bd(["update", selected.id, "--add-label=ttl-selected"])
    ws.bd(["update", other.id, "--add-label=ttl-unselected"])
    await openTree(page, ws)
    const trigger = page.getByRole("button", { name: "Label filter", exact: true })
    const row = (label: string) => page.locator("[data-multi-select-row]").filter({ has: page.getByRole("checkbox", { name: label, exact: true }) })
    await trigger.click()
    await row("ttl-selected").click()
    await page.keyboard.press("Escape")
    await page.goto(path)
    await expect(page.getByRole("heading", { name: view, exact: true })).toBeVisible()
    await expect(trigger).toHaveText("ttl-selected")
    await trigger.click()
    await expect(row("ttl-selected")).toBeVisible()
    await expect(row("ttl-unselected")).toBeVisible()
    await row("ttl-unselected").click()
    await page.keyboard.press("Escape")
    await expect(trigger).toHaveText("2 labels")
  })
}

test("Chart workspace switches clear the previous workspace's labels without visiting Beads", async ({ page, workspace: ws, statusesWorkspace }) => {
  const beads = ws.bdJson<Listed[]>(["list", "--status", "all", "--limit", "0", "--flat"])
  const target = beads.find((b) => b.title === "Critical Bug")!
  ws.bd(["update", target.id, "--add-label=ttl-chart-switch"])
  const returnTarget = statusesWorkspace.bdJson<Listed[]>(["list", "--status", "all", "--limit", "0", "--flat"])[0]
  statusesWorkspace.bd(["update", returnTarget.id, "--add-label=ttl-chart-return"])
  await openTree(page, ws)
  const trigger = page.getByRole("button", { name: "Label filter", exact: true })
  await trigger.click()
  await page.locator("[data-multi-select-row]").filter({ has: page.getByRole("checkbox", { name: "ttl-chart-switch", exact: true }) }).click()
  await page.keyboard.press("Escape")
  await page.goto("/chart")
  await expect(trigger).toHaveText("ttl-chart-switch")
  const chartIds = () => page.getByTestId("gantt-row-title").evaluateAll((rows) => rows.map((r) => (r.getAttribute("title") ?? "").split(":")[0]).sort())
  await expect.poll(chartIds).toEqual([target.id])
  for (const workspace of [statusesWorkspace, ws]) {
    await page.getByRole("button", { name: `Open ${workspace.name}`, exact: true }).click()
    await expect(page).toHaveURL(/\/chart$/)
    await expect(trigger).toHaveText("All Labels")
    const expected = workspace.bdJson<Listed[]>(["list", "--status", "all", "--limit", "0", "--flat"])
    await expect.poll(chartIds).toEqual(expected.filter((b) => b.issue_type !== "epic").map((b) => b.id).sort())
    if (workspace.id === statusesWorkspace.id) {
      await trigger.click()
      await page.locator("[data-multi-select-row]").filter({ has: page.getByRole("checkbox", { name: "ttl-chart-return", exact: true }) }).click()
      await page.keyboard.press("Escape")
      await expect.poll(chartIds).toEqual([returnTarget.id])
    }
  }
})

test("label selector supports Enter, arrow navigation, Space and Escape", async ({ page, workspace: ws }) => {
  const beads = ws.bdJson<Listed[]>(["list", "--status", "all", "--limit", "0", "--flat"])
  ws.bd(["update", beads.find((b) => b.title === "Critical Bug")!.id, "--add-label=ttl-keyboard"])
  await openTree(page, ws)
  const trigger = page.getByRole("button", { name: "Label filter", exact: true })
  await trigger.focus()
  await page.keyboard.press("Enter")
  const rows = page.locator("button[data-multi-select-row]")
  await expect(rows.first()).toBeVisible()
  await page.keyboard.press("Home")
  await expect(rows.first()).toBeFocused()
  await page.keyboard.press("ArrowDown")
  const option = rows.nth(1)
  await expect(option).toBeFocused()
  const label = await option.getByRole("checkbox").getAttribute("aria-label")
  expect(label).toBeTruthy()
  await page.keyboard.press("Space")
  await expect(option.getByRole("checkbox")).toBeChecked()
  await page.keyboard.press("Escape")
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveText(label!)
})
